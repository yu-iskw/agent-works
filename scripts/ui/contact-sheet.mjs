// Freezes the current visual captures as a dated candidate set and writes a contact sheet a person
// reviews before approving them (gate U18). Candidates are copied with their sha256, so a later
// capture run cannot change what was reviewed. Approval itself is a human step; this script never
// writes artifacts/ui/baselines/approved.
//   node scripts/ui/contact-sheet.mjs [--build <sha>]
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ARTIFACTS = 'artifacts/ui';
const SOURCE = join(ARTIFACTS, 'screenshots');
const stamp = new Date().toISOString().slice(0, 10);
const target = join(ARTIFACTS, 'baselines', `candidate-${stamp}`);
const buildIndex = process.argv.indexOf('--build');
const build = buildIndex === -1 ? 'unknown' : process.argv[buildIndex + 1];

/** Which captures show real Gemini output and which render seeded rows, for the reviewer. */
const PROVENANCE = [
  [/^running-work-/, 'Seeded running task (stub rows), rendering only'],
  [/^recoverable-failure-/, 'Seeded failed task (stub rows), rendering only'],
  [/^sign-in-/, 'Sign-in page, no generated content'],
  [/^(preferences|teammate-customization|composer-mention-menu)-/, 'Workspace controls'],
  [/./, "Carol's reviewed research task, generated by real Gemini (snapshot, no new call)"],
];

const GROUPS = [
  ['Required: conversation', /^conversation-/],
  ['Required: running work', /^running-work-/],
  ['Required: result review', /^result-review-/],
  ['Required: action approval', /^action-approval-/],
  [
    'Citation, revision changes and plan review',
    /^(citation-source|revision-changes|plan-review)-/,
  ],
  ['Lists, inbox and failure', /^(sidebar-work|sidebar-results|inbox|recoverable-failure)-/],
  ['Personalization and composer', /^(teammate-customization|preferences|composer-mention-menu)-/],
  ['Sign-in', /^sign-in-/],
];

const provenance = (name) => PROVENANCE.find(([pattern]) => pattern.test(name))?.[1] ?? '';
const escape = (text) =>
  text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

const files = readdirSync(SOURCE)
  .filter((name) => name.endsWith('.png'))
  .sort();
if (files.length === 0) {
  process.stderr.write(`No captures in ${SOURCE}. Run pnpm ui:visual first.\n`);
  process.exit(1);
}
mkdirSync(target, { recursive: true });
const manifest = files.map((name) => {
  copyFileSync(join(SOURCE, name), join(target, name));
  const sha256 = createHash('sha256')
    .update(readFileSync(join(target, name)))
    .digest('hex');
  return { name, sha256, provenance: provenance(name) };
});
writeFileSync(
  join(target, 'manifest.json'),
  `${JSON.stringify({ build, frozenAt: new Date().toISOString(), files: manifest }, null, 2)}\n`,
);

const section = ([title, pattern]) => {
  const items = manifest.filter((f) => pattern.test(f.name));
  if (items.length === 0) return '';
  const figures = items
    .map(
      (f) => `<figure><a href="${escape(join(target.replace(`${ARTIFACTS}/`, ''), f.name))}">
<img loading="lazy" src="${escape(join(target.replace(`${ARTIFACTS}/`, ''), f.name))}" alt="${escape(f.name)}"></a>
<figcaption><strong>${escape(f.name.replace('.png', ''))}</strong><br>${escape(f.provenance)}<br><code>${f.sha256.slice(0, 12)}</code></figcaption></figure>`,
    )
    .join('\n');
  return `<section><h2>${escape(title)} (${items.length})</h2><div class="grid">${figures}</div></section>`;
};

const html = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>Agent Works UI baseline candidates ${stamp}</title>
<style>
body{font:14px system-ui,sans-serif;margin:24px;color:#1b1f24;background:#f4f5f7}
h1{font-size:20px}h2{font-size:16px;margin-top:32px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(320px,1fr));gap:16px}
figure{margin:0;background:#fff;border:1px solid #dfe3e8;border-radius:8px;padding:8px}
img{width:100%;height:auto;border:1px solid #eceef1;display:block}
figcaption{font-size:12px;color:#5b6470;margin-top:6px}
.note{background:#fff7e6;border:1px solid #f0c36d;border-radius:8px;padding:12px;max-width:900px}
</style></head><body>
<h1>Agent Works UI baseline candidates, ${stamp}</h1>
<div class="note"><p><strong>${manifest.length} captures</strong> from build <code>${escape(build)}</code>, frozen in
<code>${escape(target)}</code> with sha256 in <code>manifest.json</code>. Clock frozen; the live model-call counter is masked (magenta).</p>
<p>Identity and sources are simulated. Carol's task content is real Gemini output rendered from the database; running and failed tasks are seeded rows.</p>
<p>To approve: reply "baselines approved" (optionally listing defects). To reject: list the captures and what is wrong.
After approval these exact files become <code>artifacts/ui/baselines/approved/</code> and <code>pnpm ui:visual</code> compares against them.</p></div>
${GROUPS.map(section).join('\n')}
</body></html>
`;
const sheet = join(ARTIFACTS, 'contact-sheet.html');
writeFileSync(sheet, html);
process.stdout.write(`${manifest.length} captures frozen in ${target}\n${sheet}\n`);
