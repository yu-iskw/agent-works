import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

import { formatMarkdown } from './lib/format.mjs';
import { gateApprovalRoles, gateLiveRequirements, gateTasks, gateTitles } from './lib/gates.mjs';
import { planDir, readJson, scanTasks } from './lib/scan.mjs';

const clip = (text) => (text.length > 220 ? `${text.slice(0, 217)}...` : text);
const link = (path) => path.replace(`${planDir}/`, '../');

/**
 * Lists every AWAITING_OPERATOR line in each task folder, grouped by gate. ops-05 is skipped
 * so the index never cites itself.
 */
export function renderOperatorIndex(root) {
  const lines = [
    '# Operator action index',
    '',
    'Generated by `node scripts/ops-05/render-index.mjs`; a test fails when it is stale. Every line below is work only an operator can do or approve. Nothing here is an approval. Prepare each action with the template in [templates/operator-approval.md](templates/operator-approval.md); per-task handoff files are linked where they exist. Approval is scoped to the listed action and revision.',
    '',
  ];
  let total = 0;
  const seen = new Set();
  for (const gate of ['G1', 'G2', 'G3', 'G4']) {
    lines.push(
      `## ${gate} ${gateTitles[gate]}`,
      '',
      `Approval roles: ${gateApprovalRoles[gate]}.`,
      '',
    );
    lines.push('Gate-level live proof (UNTESTED until attached):', '');
    for (const [, text, path] of gateLiveRequirements[gate])
      lines.push(`- ${text}. Handoff: \`${path}\``);
    lines.push('');
    for (const task of scanTasks(root, gateTasks[gate], { skipDirs: ['ops-05'] })) {
      const handoffs = task.files
        .map((file) => file.path)
        .filter(
          (path) =>
            !path.includes('/ops-05/') &&
            /(handoff|operator-approval|operator-real-queue)/.test(path),
        );
      const repeat = seen.has(task.id);
      seen.add(task.id);
      if (task.operatorItems.length === 0 && handoffs.length === 0) {
        lines.push(
          `### ${task.id}`,
          '',
          'No AWAITING_OPERATOR line recorded in its evidence files.',
          '',
        );
        continue;
      }
      lines.push(`### ${task.id}`, '');
      if (repeat) lines.push(`Also listed under an earlier gate; counted once in the total.`, '');
      else total += task.operatorItems.length;
      for (const path of handoffs)
        lines.push(`- Approval request: [${path.split('/').pop()}](${link(path)})`);
      for (const item of task.operatorItems)
        lines.push(
          `- \`${item.file.split('/').slice(-2).join('/')}:${item.line}\` ${clip(item.text)}`,
        );
      lines.push('');
    }
  }
  lines.push(`Total AWAITING_OPERATOR lines (each task counted once): ${total}`, '');
  return lines.join('\n');
}

const bullet = (value) => (value === null || value === undefined ? 'none' : value);

/** Open decisions O01..O08 and D-01..D-12, read from the FND-01 matrix. Never upgrades a status. */
export function renderDecisionStatus(root) {
  const matrix = readJson(root, `${planDir}/fnd-01/readiness-matrix.json`);
  const lines = [
    '# Open decisions status',
    '',
    `Generated from [fnd-01/readiness-matrix.json](../fnd-01/readiness-matrix.json) (recorded ${matrix.recordedOn}, base ${matrix.baseSha.slice(0, 7)}) by \`node scripts/ops-05/render-index.mjs\`. Rule: ${matrix.rule}`,
    '',
    'A release record cannot cite a decision as accepted unless the matrix says so. Rendering never changes a status.',
    '',
    '## D-01 to D-12',
    '',
    '| ID | Question | Owner role | Status | Blocks unrestricted production | Open items | Signoff |',
    '|---|---|---|---|---|---|---|',
    ...matrix.decisions.map(
      (item) =>
        `| ${item.id} | ${item.question} | ${item.ownerRole} | ${item.status} | ${item.blocksUnrestrictedProduction ? 'yes' : 'no'} | ${item.openItems.join(', ') || 'none'} | ${bullet(item.signoff && JSON.stringify(item.signoff))} |`,
    ),
    '',
    '## O01 to O08',
    '',
    '| ID | Decision | Owner role | Status | Blocks | Related D | Signoff |',
    '|---|---|---|---|---|---|---|',
    ...matrix.openItems.map(
      (item) =>
        `| ${item.id} | ${item.decision} | ${item.ownerRole} | ${item.status} | ${item.blockingCapability} | ${item.relatedDecisions.join(', ')} | ${bullet(item.signoff && JSON.stringify(item.signoff))} |`,
    ),
    '',
    `Open: ${matrix.decisions.filter((i) => i.status !== 'accepted').length} of ${matrix.decisions.length} decisions, ${matrix.openItems.filter((i) => i.status !== 'accepted').length} of ${matrix.openItems.length} open items.`,
    '',
  ];
  return lines.join('\n');
}

/** Usage: node scripts/ops-05/render-index.mjs. Writes the two generated files under ops-05. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = new URL('../../', import.meta.url).pathname.replace(/\/$/, '');
  const dir = join(root, planDir, 'ops-05');
  for (const [name, text] of [
    ['operator-action-index.md', renderOperatorIndex(root)],
    ['decisions-status.md', renderDecisionStatus(root)],
  ])
    writeFileSync(join(dir, name), await formatMarkdown(text, join(dir, name)));
}
